if (!UnityEditor.EditorApplication.isPlaying) throw new System.InvalidOperationException("Enter Play Mode.");
var c = UnityEngine.Object.FindFirstObjectByType<Amgen.Deepavali.FlowerPaletteController>();
var data = new UnityEditor.SerializedObject(c);
var refs = data.FindProperty("petals");
var mats = Enumerable.Range(0,refs.arraySize).Select(i=>((UnityEngine.Renderer)refs.GetArrayElementAtIndex(i).objectReferenceValue).sharedMaterial).ToArray();
var center = ((UnityEngine.Renderer)data.FindProperty("centerDisc").objectReferenceValue).sharedMaterial;
var flags=System.Reflection.BindingFlags.Instance|System.Reflection.BindingFlags.NonPublic;
var clock=c.GetType().GetField("waveStartedAt",flags);
var update=c.GetType().GetMethod("Update",flags);
void Step(float t) { clock.SetValue(c,UnityEngine.Time.timeAsDouble-c.TransitionDuration*t); update.Invoke(c,null); }
c.SetState(Amgen.Deepavali.FlowerPaletteState.Base);
var mixed=Enumerable.Range(0,c.PetalCount).Select(i=>(Amgen.Deepavali.FlowerPaletteState)(i%7)).ToArray();
bool accepted=c.TransitionToLayout(mixed,Amgen.Deepavali.FlowerPaletteState.Blue);
Step(0.45f);
var originalTarget=mats[1].GetColor("_TargetBaseColor");
c.TransitionTo(Amgen.Deepavali.FlowerPaletteState.Pink);
c.TransitionTo(Amgen.Deepavali.FlowerPaletteState.Green);
bool queued=c.HasPendingTransition && mats[1].GetColor("_TargetBaseColor")==originalTarget && c.GetPetalState(1)==Amgen.Deepavali.FlowerPaletteState.Base;
Step(1.01f);
bool firstCompleted=Enumerable.Range(0,c.PetalCount).All(i=>c.GetPetalState(i)==mixed[i]);
bool nextStarted=c.IsTransitioning && !c.HasPendingTransition && c.TransitionProgress==0;
Step(1.01f);
bool latestWins=!c.IsTransitioning && Enumerable.Range(0,c.PetalCount).All(i=>c.GetPetalState(i)==Amgen.Deepavali.FlowerPaletteState.Green);
bool centerWave=center.GetFloat("_CenterSurface")==1 && center.GetFloat("_WaveProgress")==1;
c.TransitionPetalTo(0,Amgen.Deepavali.FlowerPaletteState.Blue);
c.SetPetalEmissionScale(0,0);
bool brightnessIndependent=c.IsTransitioning&&mats[0].GetFloat("_EmissionScale")==0;
Step(1.01f);
bool isolated=c.GetPetalState(0)==Amgen.Deepavali.FlowerPaletteState.Blue&&c.GetPetalState(1)==Amgen.Deepavali.FlowerPaletteState.Green;
c.TransitionTo(Amgen.Deepavali.FlowerPaletteState.Pink);
c.TransitionTo(Amgen.Deepavali.FlowerPaletteState.Orange);
c.TransitionTo(Amgen.Deepavali.FlowerPaletteState.Pink);
bool cancelPending=!c.HasPendingTransition;
c.SetState(Amgen.Deepavali.FlowerPaletteState.Base);
c.SetPetalEmissionScale(0,1);
bool reset=!c.IsTransitioning&&!c.HasPendingTransition;
var report=new { passed=accepted&&queued&&firstCompleted&&nextStarted&&latestWins&&centerWave&&brightnessIndependent&&isolated&&cancelPending&&reset, accepted,queued,firstCompleted,nextStarted,latestWins,centerWave,brightnessIndependent,isolated,cancelPending,reset };
System.IO.File.WriteAllText("output/flower-appearance/wave-validation.json",Newtonsoft.Json.JsonConvert.SerializeObject(report,Newtonsoft.Json.Formatting.Indented));
return report;
